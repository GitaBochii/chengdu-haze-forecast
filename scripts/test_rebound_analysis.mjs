import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const A=require('../project-showcase/rebound-analysis.js');
const rows=values=>values.map((aqi,i)=>({timestamp:new Date(Date.UTC(2021,0,1,i+1)).toISOString(),aqi}));
assert.equal(A.analyze(rows([90,90,90,90,90])).recovery,null);
assert.deepEqual(A.analyze(rows([90,90,90,90,90,90])).recovery,{start:1,confirmedAt:6});
assert.equal(A.analyze(rows([110,90,90,90,90,90,90])).recovery.start,2);
assert.equal(A.analyze(rows([90,90,null,90,90,90])).recovery,null);
assert.equal(A.analyze(rows([90,90,NaN,90,90,90])).recovery,null);
const gap=rows([90,90,90,90,90,90]);gap[3].timestamp=new Date(Date.UTC(2021,0,1,9)).toISOString();
assert.equal(A.analyze(gap).recovery,null);
assert.equal(A.analyze(rows([90,90,120])).rebounds[0].lowHours,2);
assert.equal(A.analyze(rows([90,90,90])).rebounds.length,0);
assert.equal(A.analyze(A.prefix(rows([90,90,120,90,90,90]),2)).rebounds.length,0);
assert.equal(A.prefix(rows([1,2,3]),0).length,0);
assert.equal(A.analyze(rows([90,90,90,90,90,90,120])).rebounds.length,0);
const payload=JSON.parse(readFileSync(new URL('../project-showcase/rebound-cases.json',import.meta.url),'utf8'));
assert.equal(A.validate(payload).cases.length,3);
const wrong=structuredClone(payload);wrong.cases[0].forecast[1].timestamp=wrong.cases[0].forecast[0].timestamp;
assert.throws(()=>A.validate(wrong),/不连续/);
const invalid=structuredClone(payload);invalid.cases[0].forecast[1].aqi=-1;
assert.throws(()=>A.validate(invalid),/无效数值/);
assert.throws(()=>A.validate({version:1,cases:[]}),/没有可用/);
console.log('15 rebound analysis and validation assertions passed');
